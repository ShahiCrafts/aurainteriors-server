test("PERF-B-06 subtree: getAllProducts expands multiple roots in one scan, identical result sets", async () => {
  const CATS = [
    { _id: "c-living", slug: "living-room", parent: null },
    { _id: "c-sofas", slug: "sofas", parent: "c-living" },
    { _id: "c-3seat", slug: "3-seater-sofas", parent: "c-sofas" },
    { _id: "c-chairs", slug: "chairs", parent: "c-living" },
    { _id: "c-bedroom", slug: "bedroom", parent: null },
    { _id: "c-beds", slug: "beds", parent: "c-bedroom" },
  ];
  const q = (result) => {
    const query = {
      populate() {
        return query;
      },
      select() {
        return query;
      },
      sort() {
        return query;
      },
      skip() {
        return query;
      },
      limit() {
        return query;
      },
      lean() {
        return query;
      },
      then(onF, onR) {
        return Promise.resolve(result).then(onF, onR);
      },
      catch(onR) {
        return Promise.resolve(result).catch(onR);
      },
    };
    return query;
  };
  let categoryFindCalls = 0;
  const calls = { productFind: [] };
  stubModule("models/category.model", {
    find: (filter) => {
      categoryFindCalls++;
      if (filter && filter.slug && Array.isArray(filter.slug.$in)) {
        const wanted = new Set(filter.slug.$in);
        return q(CATS.filter((c) => wanted.has(c.slug)));
      }
      return q(CATS);
    },
    // NO getDescendantIds on purpose.
  });
  stubModule("models/product.model", {
    find: (filter) => {
      calls.productFind.push(filter);
      return q([]);
    },
    countDocuments: async () => 0,
  });
  stubModule("middleware/upload.middleware", {
    deleteFile: async () => {},
    deleteFiles: async () => {},
  });
  delete require.cache[path.join(repo, "controllers/product.controller.js")];
  const productCtrl = require(
    path.join(repo, "controllers/product.controller.js"),
  );
  const res = mockRes();
  const next = mockNext();
  productCtrl.getAllProducts(
    { query: { categories: "living-room,bedroom" }, headers: {} },
    res,
    next,
  );
  await until(() => res.body !== undefined || next.error !== undefined);
  assert.equal(
    next.error,
    undefined,
    `handler errored: ${next.error && next.error.message}`,
  );
  assert.equal(res.statusCode, 200);
  const got = [...calls.productFind[0].category.$in].map(String).sort();
  assert.deepEqual(
    got,
    ["c-3seat", "c-bedroom", "c-beds", "c-chairs", "c-living", "c-sofas"],
    "union of both subtrees, roots included",
  );
  assert.equal(
    categoryFindCalls,
    2,
    "one slug-resolution find + ONE expansion scan (was 1 + N full scans)",
  );
});

