const catalogCache = require(path.join(repo, "utils/catalogCache"));

test("PERF-B-01 catalogCache: TTL defaults to 45s and 0 disables", () => {
  assert.equal(catalogCache.ttlMs({}), 45000);
  assert.equal(catalogCache.ttlMs({ CATALOG_CACHE_TTL_MS: "0" }), 0);
  assert.equal(catalogCache.ttlMs({ CATALOG_CACHE_TTL_MS: "5000" }), 5000);
  assert.equal(catalogCache.ttlMs({ CATALOG_CACHE_TTL_MS: "junk" }), 45000);
});

test("PERF-B-01 catalogCache: canonical keys are order-insensitive; set/get/invalidate/disabled", () => {
  catalogCache.invalidateCatalogCache();
  const k1 = catalogCache.keyFor({ b: "2", a: "1" });
  const k2 = catalogCache.keyFor({ a: "1", b: "2" });
  assert.equal(k1, k2, "sorted canonical key");
  assert.equal(catalogCache.get(k1, {}), undefined, "miss before set");
  catalogCache.set(k1, { status: "success", data: { products: [1, 2] } }, {});
  assert.deepEqual(
    catalogCache.get(k1, {}),
    { status: "success", data: { products: [1, 2] } },
    "hit after set",
  );
  // Stored as JSON: mutating the returned copy must not corrupt the entry.
  const hit = catalogCache.get(k1, {});
  hit.data.products.push(3);
  assert.deepEqual(catalogCache.get(k1, {}).data.products, [1, 2]);
  catalogCache.invalidateCatalogCache();
  assert.equal(catalogCache.get(k1, {}), undefined, "invalidate clears");
  catalogCache.set(k1, { x: 1 }, { CATALOG_CACHE_TTL_MS: "0" });
  assert.equal(
    catalogCache.get(k1, {}),
    undefined,
    "disabled TTL stores nothing",
  );
  // Expiry: a 1ms TTL entry is gone after it lapses.
  catalogCache.set(k1, { x: 2 }, { CATALOG_CACHE_TTL_MS: "60000" });
  assert.deepEqual(
    catalogCache.get(k1, { CATALOG_CACHE_TTL_MS: "1" }),
    { x: 2 },
    "entry still fresh at read time is returned",
  );
});

test("PERF-B-01 catalogCache: isAnonymousRequest rejects any credential", () => {
  assert.equal(catalogCache.isAnonymousRequest({ headers: {} }), true);
  assert.equal(
    catalogCache.isAnonymousRequest({ headers: {}, user: { _id: "u1" } }),
    false,
  );
  assert.equal(
    catalogCache.isAnonymousRequest({ headers: { authorization: "Bearer x" } }),
    false,
  );
  assert.equal(
    catalogCache.isAnonymousRequest({ headers: { cookie: "jwt=x" } }),
    false,
  );
  assert.equal(
    catalogCache.isAnonymousRequest({
      headers: { cookie: "guestSessionId=x" },
    }),
    true,
  );
});

