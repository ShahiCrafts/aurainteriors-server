test("PERF-B-06 hierarchy: ancestorsForParent matches the old per-depth walk on fixtures", async () => {
  // Tree: root <- mid <- leaf; cycA <-> cycB (corrupt cycle)
  const DOCS = [
    { _id: "root", parent: null },
    { _id: "mid", parent: "root" },
    { _id: "leaf", parent: "mid" },
    { _id: "cycA", parent: "cycB" },
    { _id: "cycB", parent: "cycA" },
  ];
  const q = (result) => {
    const query = {
      select() {
        return query;
      },
      lean() {
        return query;
      },
      then(onF, onR) {
        return Promise.resolve(result).then(onF, onR);
      },
      catch(onR) {
        return Promise.resolve(result).catch(onR);
      },
    };
    return query;
  };
  stubModule("models/category.model", { find: () => q(DOCS) });
  delete require.cache[
    path.join(repo, "services/categoryHierarchy.service.js")
  ];
  const { ancestorsForParent } = require(
    path.join(repo, "services/categoryHierarchy.service.js"),
  );
  assert.deepEqual(await ancestorsForParent(null), []);
  assert.deepEqual(await ancestorsForParent("root"), ["root"]);
  assert.deepEqual(await ancestorsForParent("mid"), ["root", "mid"]);
  assert.deepEqual(await ancestorsForParent("leaf"), ["root", "mid", "leaf"]);
  assert.deepEqual(
    await ancestorsForParent("missing"),
    ["missing"],
    "unknown parent behaves like the old findById walk",
  );
  assert.deepEqual(
    await ancestorsForParent("cycA"),
    ["cycB", "cycA"],
    "cycle truncates exactly like the old walk",
  );
});

