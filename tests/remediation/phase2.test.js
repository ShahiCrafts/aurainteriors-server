test("PERF-B-05 registryCache: loader runs once per TTL window and key; invalidate re-runs it", async () => {
  registryCache.invalidateAttributeRegistryCache();
  let calls = 0;
  const loader = async () => {
    calls++;
    return [{ key: `k${calls}` }];
  };
  const a = await registryCache.getAttributeDefinitionsCached("all", loader);
  const b = await registryCache.getAttributeDefinitionsCached("all", loader);
  assert.equal(calls, 1, "second call within TTL is a cache hit");
  assert.deepEqual(b, a);
  await registryCache.getAttributeDefinitionsCached("active", loader);
  assert.equal(calls, 2, "a different key loads separately");
  registryCache.invalidateAttributeRegistryCache();
  await registryCache.getAttributeDefinitionsCached("all", loader);
  assert.equal(calls, 3, "invalidate forces a reload");
});

