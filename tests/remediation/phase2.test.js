const publicCache = require(
  path.join(repo, "middleware/publicCache.middleware"),
);

function runPublicCache(req) {
  const headers = {};
  let nextCalled = false;
  publicCache(
    req,
    {
      setHeader: (k, v) => {
        headers[k] = v;
      },
    },
    () => {
      nextCalled = true;
    },
  );
  return { headers, nextCalled };
}

test("PERF-B-01 publicCache: anonymous GET gets the public Cache-Control header", () => {
  const { headers, nextCalled } = runPublicCache({
    method: "GET",
    headers: {},
  });
  assert.equal(nextCalled, true);
  assert.equal(
    headers["Cache-Control"],
    "public, max-age=60, stale-while-revalidate=300",
  );
});

test("PERF-B-01 publicCache: jwt cookie or Authorization header suppresses the header", () => {
  for (const headers of [
    { cookie: "jwt=abc123; other=1" },
    { cookie: "other=1; jwt=abc123" },
    { authorization: "Bearer abc123" },
  ]) {
    const { headers: set } = runPublicCache({ method: "GET", headers });
    assert.equal(set["Cache-Control"], undefined, JSON.stringify(headers));
  }
  // A non-jwt cookie alone does not suppress it.
  const { headers: set } = runPublicCache({
    method: "GET",
    headers: { cookie: "guestSessionId=x" },
  });
  assert.equal(
    set["Cache-Control"],
    "public, max-age=60, stale-while-revalidate=300",
  );
});

test("PERF-B-01 publicCache: non-GET requests never get the header", () => {
  for (const method of ["POST", "PATCH", "DELETE", "PUT"]) {
    const { headers } = runPublicCache({ method, headers: {} });
    assert.equal(headers["Cache-Control"], undefined, method);
  }
});

test("PERF-B-01 publicCache: ETag is generated by Express defaults and If-None-Match yields 304", async () => {
  const express = require("express");
  const app = express();
  app.get("/probe", publicCache, (req, res) => res.json({ ok: true }));
  const server = await new Promise((resolve) => {
    const s = app.listen(0, "127.0.0.1", () => resolve(s));
  });
  const get = (headers = {}) =>
    new Promise((resolve, reject) => {
      http
        .get(
          {
            host: "127.0.0.1",
            port: server.address().port,
            path: "/probe",
            headers,
          },
          (res) => {
            let body = "";
            res.on("data", (c) => {
              body += c;
            });
            res.on("end", () =>
              resolve({ status: res.statusCode, headers: res.headers, body }),
            );
          },
        )
        .on("error", reject);
    });
  try {
    const first = await get();
    assert.equal(first.status, 200);
    assert.equal(
      first.headers["cache-control"],
      "public, max-age=60, stale-while-revalidate=300",
    );
    assert.ok(
      first.headers.etag,
      "Express default ETag must be present (app.js does not disable it)",
    );
    const second = await get({ "If-None-Match": first.headers.etag });
    assert.equal(
      second.status,
      304,
      "conditional request must be answered 304 by Express",
    );
    const authed = await get({ Cookie: "jwt=abc" });
    assert.equal(authed.headers["cache-control"], undefined);
  } finally {
    await new Promise((resolve) => server.close(resolve));
  }
});

